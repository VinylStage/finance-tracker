'use strict';

// 할부 상태를 SQL 안에서 계산하는 조각(#205).
//
// ─────────────────────────────────────────────────────────────────────────
// 왜 라우트에서 빼는가
//
// 경계 조건(`>=` 인가 `>` 인가)이 이 파일의 핵심인데, 라우트 안에 두면 그것을
// **오늘 날짜로만** 검사할 수 있다. 경계는 "마지막 청구월의 다음 달 1일" 이라
// 한 달에 하루뿐이고, 나머지 날에는 `>=` 를 `>` 로 바꿔도 어떤 테스트도 깨지지
// 않는다 — 실제로 그 상태였다.
//
// 조각을 내보내면 테스트가 `@today` 에 임의의 날짜를 넣어 경계 양쪽을 직접
// 짚을 수 있다. 문자열을 테스트가 다시 적지 않으므로, 한쪽만 고쳐질 일도 없다.
//
// 별칭 `i` 를 쓴다. 쓰는 쪽이 `FROM installments i` 로 맞춘다.

// 청구가 끝나는 날. 시작월 1일에 개월수를 더하면 마지막 청구월의 다음 달 1일이
// 되고, 그 날이 되면 청구가 끝난 것으로 본다.
const BILLING_END = `
  strftime('%Y-%m-%d', date(i.start_billing_month || '-01', '+' || i.months || ' months'))
`;

// 저장하지 않고 계산한다.
//
// 예전에는 `status` 컬럼에 저장하고 GET 이 돌 때마다 만료된 행을 '완료' 로
// UPDATE 하는 스윕이 있었다. 조회가 데이터를 바꾸는 구조라 감사 로그에 사용자가
// 하지 않은 쓰기가 쌓였고, 그것을 actor='system' 으로 가리고 있었다(#297·#298).
//
// 저장된 값은 어차피 정본이 아니었다. `installmentsDueForMonth()` 는 저장된
// status 를 믿지 않고 청구 기간을 직접 계산했고(FND-05), `dataIntegrity` 는
// "종료됐어야 하는데 진행중" 을 무결성 위반으로 점검하고 있었다 — 캐시가
// 틀어지는 것이 정상 동작 범위라는 뜻이었다.
//
// 조기 완납(`paid_off_on`)을 함께 본다. 그 날짜가 있으면 회차 생성이 거기서
// 잘리므로(`buildInstallmentRows`) 청구는 원래 개월수보다 먼저 끝난다. 옛
// 스윕은 이 컬럼을 안 봐서 이미 끝난 할부를 몇 달씩 '진행중' 으로 두었다.
const STATUS_EXPR = `
  CASE
    WHEN i.paid_off_on IS NOT NULL AND @today >= i.paid_off_on THEN '완료'
    WHEN @today >= ${BILLING_END} THEN '완료'
    ELSE '진행중'
  END
`;

module.exports = { BILLING_END, STATUS_EXPR };
