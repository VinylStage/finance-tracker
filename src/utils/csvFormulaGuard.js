'use strict';

// CSV 수식 인젝션 방어와 그 역연산(#460, CWE-1236).
//
// ─────────────────────────────────────────────────────────────────────────
// 무엇을 막나
//
// Excel·LibreOffice·Google Sheets 는 셀 값이 `= + - @` 로 시작하면 **수식으로
// 해석해 연다.** `=HYPERLINK(...)` 나 `=cmd|'/c ...'!A0` 계열이 여기 실린다.
//
// 가맹점명이 도달 경로다. 메모는 사용자가 직접 쓰지만 **가맹점명은 카드사 엑셀
// 임포트가 넣는다** — 값의 출처가 사용자 본인이 아니다.
//
// ─────────────────────────────────────────────────────────────────────────
// 왜 따옴표 감싸기로는 안 되나
//
// RFC 4180 의 `"..."` 는 **구분자와 줄바꿈을 위한 것이지 수식 해석을 막지
// 못한다.** 스프레드시트는 감싼 따옴표를 벗긴 뒤 남은 값을 보고 판정한다.
// 이슈 #460 의 B안이 이것이었고, 실행해 보면 그대로 수식이 된다.
//
// ─────────────────────────────────────────────────────────────────────────
// 왜 접두 어포스트로피인가
//
// 스프레드시트가 "이 셀은 글자다" 로 읽는 표준 표기다. 값 자체를 바꾸지 않고
// (공백·탭을 넣는 C안은 값이 달라진다) **되돌릴 수 있다** — 그게 이 파일에
// `unguardFormula` 가 같이 있는 이유다.
//
// 짝을 한 파일에 두는 이유는 한쪽만 고쳐지는 것을 막기 위해서다. 붙이는 쪽만
// 고치면 내보낸 파일을 다시 못 읽고, 벗기는 쪽만 고치면 멀쩡한 값이 깎인다.

// 스프레드시트가 수식 시작으로 읽는 문자.
const FORMULA_LEAD = ['=', '+', '-', '@'];

// 값 앞에 `'` 를 붙인다. 대상이 아니면 그대로 돌려준다.
//
// 감싸기(따옴표)보다 **먼저** 돈다. 붙인 뒤에 감싸기 판정을 해야 `=1+1,x` 같은
// 값이 `"'=1+1,x"` 로 온전히 나간다.
function guardFormula(value) {
  if (typeof value !== 'string' || value === '') return value;
  return FORMULA_LEAD.includes(value[0]) ? `'${value}` : value;
}

// `guardFormula` 를 되돌린다.
//
// **우리가 붙인 것만 벗긴다.** 뒤따르는 문자가 수식 시작 문자일 때에만 벗기므로,
// `'안녕` 처럼 어포스트로피로 시작하는 멀쩡한 값은 건드리지 않는다. 조건 없이
// 선행 `'` 를 벗기면 그런 값이 매번 한 글자씩 깎인다.
function unguardFormula(value) {
  if (typeof value !== 'string' || value.length < 2) return value;
  if (value[0] !== "'") return value;
  return FORMULA_LEAD.includes(value[1]) ? value.slice(1) : value;
}

module.exports = { FORMULA_LEAD, guardFormula, unguardFormula };
