// 금액 표기 정본(#236).
//
// ─────────────────────────────────────────────────────────────────────────
// 왜 한 곳으로 모으는가
//
// 같은 한 줄이 20개 파일에 글자 그대로 복사돼 있었다.
//
//     Number(n || 0).toLocaleString('ko-KR') + '원'
//
// 지금은 우연히 전부 같지만, **한 곳만 바뀌면 화면마다 금액 표기가 갈린다.**
// 음수 표기·0원 처리·통화 기호 위치 같은 규칙이 생기면 스무 번 고쳐야 하고
// 그중 하나를 빠뜨릴 확률이 높다.
//
// 이 저장소에서 같은 패턴이 이미 두 번 문제가 됐다 — #211(서버 숫자 검증)과
// #231(에러 문구). 규칙이 흩어져 있으면 **시정이 진단 범위만큼만 이루어진다.**
//
// ─────────────────────────────────────────────────────────────────────────
// 로케일을 반드시 명시한다
//
// 생략하면 실행 환경의 로케일을 따라가고, de-DE 같은 환경에서 `1.234.567` 로
// 나온다. 이 앱은 원화 표기 하나만 쓴다.
// ─────────────────────────────────────────────────────────────────────────

const LOCALE = 'ko-KR';

/**
 * 금액을 '1,234,567원' 으로 적는다.
 *
 * 규칙은 #291 이 balanceView 에 세워 둔 것을 그대로 가져왔다. 통합하면서 느슨한
 * 쪽으로 맞추면 그쪽이 테스트로 잠가 둔 보장이 깨진다.
 *
 *   - null / undefined / NaN / 숫자가 아닌 문자열 → '0원'.
 *     화면에 'NaN원' 이 뜨는 것보다 낫다. 다만 **0 과 '모름' 을 구분해야 하는
 *     자리에서는 쓰지 말 것** — 여기서는 둘 다 '0원' 이 된다.
 *   - 소수는 반올림한다. 원 단위 아래는 표기하지 않는다. 이자·예측처럼 소수가
 *     나오는 계산이 있어서 필요하다.
 */
export function formatWon(n) {
  const num = Number(n);
  if (n === null || n === undefined || Number.isNaN(num)) return '0원';
  return `${Math.round(num).toLocaleString(LOCALE)}원`;
}

/**
 * 단위 없이 자릿수만 구분한다 — '1,234,567'.
 *
 * 축 라벨처럼 '원' 이 반복되면 오히려 읽기 나쁜 자리에서 쓴다.
 */
export function formatNumber(n) {
  return Number(n || 0).toLocaleString(LOCALE);
}
