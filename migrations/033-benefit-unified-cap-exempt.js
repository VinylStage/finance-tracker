// 카드 월 통합 한도에 들지 않는 혜택을 표시한다(#648).
//
// ─────────────────────────────────────────────────────────────────────────
// 무엇이 없었나
//
// `card_threshold_tiers.monthly_cap`(030) 은 «그 구간에서 이 카드가 받을 수 있는
// 전부» 로 걸린다. 어느 혜택이 골라지든 마지막에 한 번 더 자른다.
//
// 그런데 약관에는 **그 상한 밖에 있는 혜택**이 있다.
//
//   하나 나라사랑카드(체크)
//     1~9번 항목    캐시백      → 구간별 월 통합 한도 5,000 ~ 50,000원
//     10번 놀이공원  현장할인 50% 월 1회  → 이 상한 **밖**
//
// 상품설명서에서 통합 한도 칸은 캐시백 행들을 가로질러 병합돼 있다. 10번은 그
// 병합 범위 밖이고, 종류도 캐시백이 아니라 현장할인이다.
//
// 표시할 자리가 없으면 에버랜드 40,000원 결제(50% = 20,000원)가 실적 10만원
// 구간에서 **5,000원으로 잘린다.** 같은 달에 다른 항목을 이미 썼으면 0 이 된다.
//
// ─────────────────────────────────────────────────────────────────────────
// 왜 컬럼인가
//
// 「실적 조건이 붙는가」 를 031 이 컬럼으로 갈랐다. 「통합 한도에 드는가」 도
// **같은 종류의 질문**인데 저장할 자리가 없었다.
//
// 지금까지는 「구간을 가리키는가」 · 「실적 조건이 붙는가」 · 「통합 한도에
// 드는가」 셋이 우연히 겹쳐 왔을 뿐이다. 이 카드가 그 겹침을 깬다 — 놀이공원은
// 실적 조건이 붙으면서 통합 한도 밖이다. 추론으로는 못 가른다.
//
// 기본값은 0(통합 한도에 든다)이다. **백필하지 않는다** — 지금 들어 있는 줄은
// 전부 그 동작이었으므로 이 변경으로 계산이 달라지지 않는다.
//
// `threshold_exempt`(031) 와 같은 층이다.

function up(db) {
  const cols = db.prepare('PRAGMA table_info(card_benefits)').all().map((c) => c.name);
  if (!cols.includes('unified_cap_exempt')) {
    db.exec('ALTER TABLE card_benefits ADD COLUMN unified_cap_exempt INTEGER NOT NULL DEFAULT 0');
  }
}

