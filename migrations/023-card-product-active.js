'use strict';

// 카드 상품에 활성 여부를 둔다(#410).
//
// ─────────────────────────────────────────────────────────────────────────
// 왜 하드 삭제를 그만두는가
//
// 지금은 카드를 지우면 그 카드로 지정됐던 거래의 card_product_id 가 NULL 로
// 돌아간다. 거래를 지우지 않으려는 의도였지만(#306), 그 결과 **NULL 의 뜻이
// 두 가지**가 됐다.
//
//   1. 한 번도 지정된 적 없다
//   2. 사용자가 그 카드를 지웠다
//
// 카드 전략 계산은 NULL 을 보면 결제수단으로 되짚는다 — 그 결제수단에 상품이
// 딱 하나면 그것이 정답이라고 본다. 2번에서는 이 추론이 틀린다. **지운 카드가
// 후보에서 빠져 있으니 남은 하나가 정답처럼 보인다.** 그러면 지운 카드의 과거
// 지출이 남은 카드의 실적으로 넘어간다 — 화면에는 그럴듯한 숫자가 뜨고
// unknownCard 로도 안 잡힌다.
//
// 비활성화는 이 문제를 뿌리에서 없앤다. 행이 남으므로 거래의 참조도 남고,
// **NULL 은 다시 "한 번도 지정된 적 없다" 하나만 뜻하게 된다.** 되짚기 로직을
// 고칠 필요도 없다 — 비활성 카드가 후보에 그대로 있어 "상품이 딱 하나" 조건이
// 성립하지 않으므로 애초에 되짚지 않는다.
//
// ─────────────────────────────────────────────────────────────────────────
// 왜 컬럼 하나인가
//
// 삭제 시각을 남기는 방법(deleted_at)도 있다. 그러면 "그 카드가 살아 있던
// 기간" 을 알 수 있지만, 이 앱은 그 정보를 쓸 곳이 없다 — 거래가 카드를 직접
// 가리키므로 시점으로 되짚을 이유가 없다. 쓰지 않을 정보를 위해 컬럼을 늘리지
// 않는다.
//
// is_active 는 payment_methods·categories·accounts 가 이미 쓰는 이름이다.
// 같은 뜻에 같은 이름을 쓴다.
//
// **기존 행은 전부 활성이다.** DEFAULT 1 이라 백필이 따로 필요 없다.
//
// 감사 트리거는 여기서 다시 만들지 않는다. 마이그레이션 러너가 하나라도
// 적용되면 체인 끝에서 rebuildAuditTriggers 를 부른다(#346).
function up(db) {
  const cols = db.prepare('PRAGMA table_info(card_products)').all().map((c) => c.name);
  if (!cols.includes('is_active')) {
    db.exec(`ALTER TABLE card_products ADD COLUMN is_active INTEGER NOT NULL DEFAULT 1`);
  }

  // 목록·선택지는 거의 항상 활성만 본다. 카드 수가 많지 않아 성능 때문은
  // 아니고, 조건이 빠진 조회를 나중에 찾기 쉽게 하려는 것이다.
  db.exec(`
    CREATE INDEX IF NOT EXISTS idx_card_products_active
      ON card_products(is_active);
  `);
}

module.exports = { up };
