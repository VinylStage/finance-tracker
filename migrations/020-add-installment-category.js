'use strict';

// 할부에 가맹점 카테고리(#316).
//
// ─────────────────────────────────────────────────────────────────────────
// 왜 필요한가
//
// #315 가 할부 정책에 카테고리 차원을 넣었다 — 같은 카드라도 "온라인쇼핑 6개월
// 무이자" 처럼 카테고리별 예외가 존재하기 때문이다. `resolvePolicy` 도 카테고리를
// 받는다.
//
// 그런데 **할부 쪽에 카테고리가 없어서 그 인자를 채울 수가 없었다.** 정책은
// 카테고리별로 등록되는데 조회는 기본 정책으로만 떨어져, #315 가 만든 차원이
// 실제로는 한 번도 쓰이지 않는 상태였다.
//
// ─────────────────────────────────────────────────────────────────────────
// 번호가 020 인 이유
//
// 019 는 다른 세션의 카드 혜택(#274)이 먼저 잡았다. 마이그레이션 번호는 세션 간
// 공유 자원이라 착수 직전에 원격 브랜치까지 확인해야 한다.
//
// ─────────────────────────────────────────────────────────────────────────
// nullable 인 이유
//
// 기존 할부에는 카테고리가 없다. NOT NULL DEFAULT 로 아무 카테고리나 박으면
// "사용자가 온라인쇼핑이라고 지정했다" 와 "아직 모른다" 를 구분할 수 없게 된다.
// 모르는 것은 모르는 채로 둔다 — 그래야 기본 정책으로 떨어지는 지금 동작이
// 그대로 유지되고, 과거 할부의 청구액이 소급해서 바뀌지 않는다.
//
// ─────────────────────────────────────────────────────────────────────────
// 감사 트리거는 여기서 부르지 않는다
//
// 017 의 감사 트리거는 생성 시점의 컬럼 목록을 굳히므로, 컬럼이 늘면 새 컬럼이
// 캡처에서 조용히 빠진다. 그래서 재생성이 필요하다.
//
// 다만 그 호출은 **러너가 한다**(#346 / `src/db/migrate.js`). 마이그레이션마다
// 작성자가 기억해야 하는 구조였던 것을 체인 적용 후 한 번 도는 방식으로 옮겼다.
// 여기서 또 부르면 같은 일을 두 번 한다.

function up(db) {
  const cols = db.prepare('PRAGMA table_info(installments)').all().map((c) => c.name);
  if (!cols.includes('category_id')) {
    db.exec(`
      ALTER TABLE installments
      ADD COLUMN category_id INTEGER REFERENCES categories(id)
    `);
  }

  // 정책 조회가 (카드 + 카테고리 + 개월수) 로 도는 경로를 받쳐 준다.
  db.exec(`
    CREATE INDEX IF NOT EXISTS idx_installments_category
      ON installments(category_id)
  `);
}

module.exports = { up };
