// 가맹점-카테고리 매핑 캐시(#275).
//
// ─────────────────────────────────────────────────────────────────────────
// 왜 캐시하는가
//
// 같은 가맹점이 거래마다 반복해서 나온다. 매번 외부 API 를 부르면 쿼터를
// 소진하고 입력이 느려진다. 가맹점명은 카드 명세서에서 오는 값이라 표기가
// 안정적이다 — 캐시가 잘 맞는 조건이다.
//
// ─────────────────────────────────────────────────────────────────────────
// source 를 남기는 이유
//
// **사용자가 손으로 고친 매핑을 API 결과가 덮으면 안 된다.** 사용자는 그
// 가맹점이 자기에게 무엇인지 안다 — "스타벅스" 가 업무 접대인 사람과 개인
// 커피인 사람이 다르다. 외부 API 는 그걸 모른다.
//
//   'manual'  사용자가 지정. 무엇도 덮지 못한다
//   'kakao'   외부 API 결과
//   'history' 같은 가맹점의 과거 거래에서 추론
//
// 조회 우선순위는 manual > 캐시 > API > 이력이고, 그 판단은 서비스가 한다.
// 이 테이블은 기록만 한다.
//
// ─────────────────────────────────────────────────────────────────────────
// category_id 를 nullable 로 두는 이유
//
// 카카오가 분류를 줬는데 앱 카테고리로 옮길 수 없는 경우가 있다(미분류로
// 떨어지는 분류들). 그때도 **조회했다는 사실은 남겨야** 한다 — 안 남기면
// 다음에 또 부르고 또 실패한다. 쿼터만 소진된다.
//
// ─────────────────────────────────────────────────────────────────────────
// 감사 트리거를 여기서 재생성하지 않는다
//
// 새 테이블은 감사 캡처 대상이지만, 그 재생성은 runMigrations 가 체인 끝에서
// 한 번에 책임진다(#346).

