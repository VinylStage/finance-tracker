// 건당 결제액 상한을 담는다(#638).
//
// ─────────────────────────────────────────────────────────────────────────
// 무엇이 없었나
//
// `min_amount` 는 «건당 N원 **이상**» 만 표현한다. 카드 약관에는 그 반대도 흔하다.
//
//   하나 나라사랑카드(체크)  군마트 30%  «건당 10만원 **미만** 결제»
//                            군마트 20%  «건당 10만원 **이상** 결제»
//
// 두 줄이 금액으로 갈리는 구조인데 상한을 못 적어서, 10만원 이상 결제에도 30% 줄이
// 후보로 잡혔다. 계산기는 예상 금액이 큰 쪽을 고르므로 30% 를 골랐고, 그 줄의
// 한도가 작아 결과가 실제보다 **적게** 나왔다.
//
// 「소액 결제에만 높은 요율」은 카드사가 흔히 쓰는 방식이라 이 카드만의 사정이 아니다.
//
// ─────────────────────────────────────────────────────────────────────────
// 왜 컬럼인가
//
// `min_amount` 가 이미 컬럼이다. 금액 하한과 상한은 **한 쌍**이라 같은 자리에 둔다.
// 조건 하나는 컬럼이고 짝은 `rule_json` 안이면, 후보를 거를 때 두 군데를 봐야 하고
// 화면도 두 곳에서 읽어야 한다.
//
// 「이 결제가 이 혜택 대상인가」를 정하는 값이라 후보 선택 단계에서 본다 —
// `payment_style`(028) · `card_threshold_tier_id`(026) · `threshold_exempt`(031) 과
// 같은 층이다.
//
// NULL 이면 상한 없음이다. **백필하지 않는다** — 지금 들어 있는 줄은 전부 상한이
// 없었으므로 이 변경으로 계산이 달라지지 않는다.
//
// 경계는 «미만» 이다. 약관이 «10만원 미만» 이라고 쓰므로 `amount < max_amount` 로
// 읽는다. 하한(`min_amount`)이 «이상»(`>=`)인 것과 짝이 맞는다 — 같은 값을 두 줄에
// 넣으면 빈틈도 겹침도 없다.

function up(db) {
  const cols = db.prepare('PRAGMA table_info(card_benefits)').all().map((c) => c.name);
  if (!cols.includes('max_amount')) {
    db.exec('ALTER TABLE card_benefits ADD COLUMN max_amount INTEGER');
  }
}

module.exports = { up };
