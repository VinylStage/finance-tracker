'use strict';

// 혜택 규칙을 선언으로 저장한다(#564).
//
// ─────────────────────────────────────────────────────────────────────────
// 무엇이 막혀 있었나
//
// `card_benefits.rate` 가 `REAL NOT NULL` 이고 계산이 `amount × rate / 100` 이라,
// **요율이 아닌 혜택을 표현할 자리가 없다.** 실제로 «전월 30만 이상이면 이번 달
// 3,000원» 같은 정액 구간형 카드가 들어오지 못했다.
//
// ─────────────────────────────────────────────────────────────────────────
// 왜 컬럼을 더 늘리지 않나
//
// `flat_amount` 를 더하면 다음 유형에서 또 컬럼이 는다. 카드사마다 혜택 구조가
// 다르므로 이 방향은 끝이 없고, 안 쓰는 칸이 NULL 로 쌓인다.
//
// 대신 **규칙 자체를 선언으로 저장하고** 유형별 해석기가 읽는다.
//
//   {"kind":"rate",         "rate":0.7}
//   {"kind":"flat_monthly", "tiers":[{"min_spend":300000,"amount":3000}]}
//
// 유형이 늘어도 스키마는 그대로다. 해석기 하나가 붙을 뿐이다.
//
// ─────────────────────────────────────────────────────────────────────────
// 공유 스키마 하나로 간다
//
// 카드마다 혜택이 달라도 **카드별 특수 코드로 새지 않는다.** 새 카드가 안 맞으면
// «이 카드만의 예외» 가 아니라 «일반적으로 어떤 유형인가» 를 먼저 묻고, 정말 새
// 유형일 때만 해석기를 더한다. 해석기 이름도 카드가 아니라 **유형**의 이름이다.
//
// 그래서 `{"kind":"custom"}` 같은 탈출구를 **만들지 않는다.** 그것이 카드별
// 특수 코드가 스며드는 문이다. 필요해지는 카드가 실제로 나타나면 그때 연다.
//
// ─────────────────────────────────────────────────────────────────────────
// 기존 행은 그대로 동작한다
//
// 백필하지 않는다. 읽는 쪽이 `rule_json` 이 비어 있으면 `rate` 컬럼을 보고
// `{kind:'rate'}` 로 간주한다. 021 이 `billing_month` 에서, 026 이
// `prev_month_threshold` 에서 쓴 것과 같은 방식이다 — 대량 변경은 ADR 0008
// 대상이고, 읽기에서 떨어뜨리면 백필 없이도 동작한다.

function up(db) {
  const cols = db.prepare('PRAGMA table_info(card_benefits)').all().map((c) => c.name);
  if (!cols.includes('rule_json')) {
    db.exec('ALTER TABLE card_benefits ADD COLUMN rule_json TEXT');
  }
}

module.exports = { up };
